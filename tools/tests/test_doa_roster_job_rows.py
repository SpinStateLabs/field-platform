"""R2-04: the Phase G job rows live in manifests/doa-roster.example.yaml, and a
roster regenerated by tools/generate_doa_roster.py keeps them (--job-rows).

Before R2-04 the job rows (C-13: job-provision-gb10, job-renewal-rog) sat in a
companion example no estate read and no tool merged, and the generator builds
rows only from the registry, the manifests and live tokens, none of which names
a job id: a regenerated roster dropped them and the next job mint was 403
D.grantor (fail closed). These tests pin, on the repository's own files:

* the folded example lets each job mint exactly its agents' scopes through the
  real DOA gate (`delegation doa check`, the route's own clauses), and still
  refuses job-renewal-gb10 (a commented template until volatility-trader's
  scopes are in the repository);
* `--job-rows ROSTER` carries every `job-*` row of ROSTER verbatim into the
  generated roster, replacing a token-derived row of the same grantor;
* without it the tool says on stderr and in the header that job mints will be
  refused; a ROSTER with no job row, or one that does not load, is refused with
  nothing written.

The real-estate counterpart (a regenerated roster armed under ENFORCE, a job's
mint passing the gate) is in test_job_grantors_c13.py.
"""

from __future__ import annotations

import contextlib
import io
import json
import shutil
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

import pytest
import yaml
from typer.testing import CliRunner

TOOLS = Path(__file__).resolve().parents[1]
REPO = TOOLS.parent
sys.path.insert(0, str(TOOLS))

import generate_doa_roster as gen  # noqa: E402
from delegation_authority.cli import app as delegation_cli  # noqa: E402
from delegation_authority.doa import load_roster  # noqa: E402

EXAMPLE = REPO / "manifests" / "doa-roster.example.yaml"
DON = "Don Hagell, Spin State Labs"
JOBS = ["job-provision-gb10", "job-renewal-rog"]
SSL = ("ssl-timekeeping-agent", "ssl-invoicing-agent")
SELF_AGENTS = ("conformance-sentinel", "force-gateway", "compliance-crosswalk")
#: the agents each job mints for (design v0.4 2.2.1 + P22)
JOB_AGENTS = {"job-provision-gb10": SELF_AGENTS, "job-renewal-rog": SSL}


def _manifest(agent: str) -> dict:
    return yaml.safe_load((REPO / "manifests" / f"{agent}.yaml").read_text(encoding="utf-8"))


def _example_job_rows() -> list[dict]:
    return [r.model_dump(mode="json", exclude_none=True) for r in load_roster(EXAMPLE).grantors
            if r.grantor.startswith("job-")]


def _doa_check(roster: Path, grantor: str, agent: str, ttl_days: int = 30):
    manifest = REPO / "manifests" / f"{agent}.yaml"
    argv = ["doa", "check", "--roster", str(roster), "--grantor", grantor, "--ttl-days", str(ttl_days),
            "--manifest", str(manifest)]
    for scope in _manifest(agent)["delegation"]["scope"]:
        argv += ["--scope", scope]
    return CliRunner().invoke(delegation_cli, argv)


# --- the folded example, through the real gate ---------------------------------------


@pytest.mark.parametrize("job", JOBS)
def test_the_folded_example_lets_each_job_mint_its_agents_full_scope(job):
    for agent in JOB_AGENTS[job]:
        for ttl in (30, 31):  # renew_token mints at most 30 days; the row's ceiling is 31
            result = _doa_check(EXAMPLE, job, agent, ttl)
            assert result.exit_code == 0, result.output
            assert f"ALLOW grantor={job!r}" in result.output and f"agent='{agent}'" in result.output
        result = _doa_check(EXAMPLE, job, agent, 32)
        assert result.exit_code == 1 and "D.grantor" in result.output, result.output


def test_the_folded_example_still_refuses_job_renewal_gb10():
    """Its row is a commented template: volatility-trader's manifest (its scopes) is
    not in this repository, so nothing is invented and the gate refuses the job."""
    assert not list(REPO.glob("**/volatility-trader.yaml"))
    result = _doa_check(EXAMPLE, "job-renewal-gb10", "ssl-timekeeping-agent")
    assert result.exit_code == 1 and "D.grantor" in result.output, result.output


# --- generate_doa_roster.py --job-rows -----------------------------------------------


@pytest.fixture()
def estate(tmp_path) -> list[dict]:
    """The repository's five governed manifests, registered and active (the GB10 shape
    without volatility-trader), resolved by file name as on the estate."""
    mdir = tmp_path / "manifests"
    mdir.mkdir()
    for agent in SSL + SELF_AGENTS:
        shutil.copy(REPO / "manifests" / f"{agent}.yaml", mdir / f"{agent}.yaml")
    return [{"agent_id": a, "name": a, "owner": DON, "domain": "finance", "status": "active",
             "manifest_ref": f"/data/manifests/{a}.yaml"} for a in SSL + SELF_AGENTS]


def run(tmp_path: Path, records: list[dict], *extra: str) -> tuple[int, str, str, Path]:
    registry = tmp_path / "agents.json"
    registry.write_text(json.dumps(records), encoding="utf-8")
    out = tmp_path / "out" / "doa-roster.yaml"
    so, se = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(so), contextlib.redirect_stderr(se):
        code = gen.main(["--registry", str(registry), "--manifests", str(tmp_path / "manifests"),
                         "--out", str(out), *extra])
    return code, so.getvalue(), se.getvalue(), out


def _grantors(out: Path) -> list[dict]:
    return yaml.safe_load(out.read_text(encoding="utf-8"))["grantors"]


def test_regenerating_with_job_rows_keeps_the_examples_job_rows_verbatim(tmp_path, estate):
    code, stdout, stderr, out = run(tmp_path, estate, "--job-rows", str(EXAMPLE))
    assert code == 0, stderr
    rows = _grantors(out)
    jobs = [r for r in rows if r["grantor"].startswith("job-")]
    assert jobs == _example_job_rows()               # every field, in the example's order
    assert [r["grantor"] for r in jobs] == JOBS      # nothing invented (no job-renewal-gb10)
    assert rows[-len(jobs):] == jobs                 # appended after the generated rows
    generated = {r["grantor"]: r for r in rows[:-len(jobs)]}
    assert generated[DON]["max_ttl_days"] == 30      # the generated rows are untouched:
    assert "max_spend_usd" not in generated[DON]     # only job-* rows are carried, not the example's Don row
    assert f"  - {DON}: 10 scope(s), max_ttl_days=30\n" in stdout
    load_roster(out)
    for job, row in zip(JOBS, jobs):
        assert (f"  - {job}: {len(row['allowed_scope'])} scope(s), max_ttl_days=31 "
                "[job row carried verbatim from doa-roster.example.yaml]") in stdout
    assert ("# Job rows carried verbatim from doa-roster.example.yaml: job-provision-gb10, job-renewal-rog."
            in out.read_text(encoding="utf-8"))
    assert "no --job-rows given" not in stderr
    # and the regenerated roster passes each job's mint through the real gate
    for job in JOBS:
        for agent in JOB_AGENTS[job]:
            result = _doa_check(out, job, agent)
            assert result.exit_code == 0, result.output


def test_without_job_rows_the_regenerated_roster_has_none_and_the_tool_says_so(tmp_path, estate):
    code, _, stderr, out = run(tmp_path, estate)
    assert code == 0, stderr
    assert not [r for r in _grantors(out) if r["grantor"].startswith("job-")]
    assert "no --job-rows given" in stderr and "403 D.grantor" in stderr
    assert "# NO job rows (no --job-rows)" in out.read_text(encoding="utf-8")
    result = _doa_check(out, "job-renewal-rog", "ssl-invoicing-agent")
    assert result.exit_code == 1 and "D.grantor" in result.output, result.output


def test_a_carried_job_row_replaces_a_token_derived_row_of_the_same_grantor(tmp_path, estate):
    """After job-renewal-rog has renewed ONE agent, its id is a live token's grantor, and
    --tokens alone would roster it with that holder's scope only (and ttl 30): the next
    renewal of the OTHER agent would be refused. The carried row wins, once."""
    now = datetime.now(timezone.utc)
    tokens = tmp_path / "tokens.json"
    tokens.write_text(json.dumps([{
        "token_id": "tok-rog-1", "agent_id": "ssl-timekeeping-agent", "granted_by": "job-renewal-rog",
        "scope": ["anything"], "issued_at": (now - timedelta(days=1)).isoformat(),
        "expires_at": (now + timedelta(days=29)).isoformat(), "revoked": False,
        "revocation_id": None, "revoked_at": None}]), encoding="utf-8")
    code, stdout, stderr, out = run(tmp_path, estate, "--tokens", str(tokens))
    assert code == 0, stderr
    derived = [r for r in _grantors(out) if r["grantor"] == "job-renewal-rog"]
    assert derived and derived[0]["allowed_scope"] == _manifest("ssl-timekeeping-agent")["delegation"]["scope"]

    code, stdout, stderr, out = run(tmp_path, estate, "--tokens", str(tokens), "--job-rows", str(EXAMPLE))
    assert code == 0, stderr
    carried = [r for r in _grantors(out) if r["grantor"] == "job-renewal-rog"]
    assert carried == [r for r in _example_job_rows() if r["grantor"] == "job-renewal-rog"]
    assert ("job-renewal-rog: 10 scope(s), max_ttl_days=31 [job row carried verbatim from "
            "doa-roster.example.yaml, replaces the generated row]") in stdout
    result = _doa_check(out, "job-renewal-rog", "ssl-invoicing-agent")
    assert result.exit_code == 0, result.output


@pytest.mark.parametrize("case", ["no-job-row", "not-a-roster", "missing"])
def test_a_job_rows_file_without_job_rows_or_that_does_not_load_is_refused(tmp_path, estate, case):
    src = tmp_path / "jobs.yaml"
    if case == "no-job-row":  # the example's own Don row only: the wrong file was named
        don = [r for r in yaml.safe_load(EXAMPLE.read_text(encoding="utf-8"))["grantors"] if r["grantor"] == DON]
        src.write_text(yaml.safe_dump({"grantors": don}), encoding="utf-8")
    elif case == "not-a-roster":
        src.write_text("grantors:\n  - grantor: job-x\n    note: extra\n", encoding="utf-8")
    code, _, stderr, out = run(tmp_path, estate, "--job-rows", str(src))
    assert code == 2 and not out.exists(), stderr
    assert "REFUSED (nothing written): --job-rows" in stderr
    if case == "no-job-row":
        assert "no row whose grantor starts with 'job-'" in stderr
